def setup_vizier_study(parameter_shape):
    # Algorithm, search space, and metrics.
    study_config = vz.StudyConfig(algorithm='GAUSSIAN_PROCESS_BANDIT')
    # The algorithm keyword can be used to try out different optimizers. A list
    # can be found at: https://github.com/google/vizier/blob/main/vizier/_src/service/policy_factory.py
    # Add a vizier study parameter for every optimizable parameter.
    # This is possibly not the right way to set up this problem but it is the
    # easiest way. But it looks like add_param supports an "index" argument
    # that effectively does the same thing internally, so maybe it is correct.
    ranges = [range(n) for n in parameter_shape]
    for indices in iter_product(*ranges):
        index_name = '_'.join([str(n) for n in indices])
        parameter_name = f'value_{index_name}'
        # We can try configuring this as either bool (categorical) or
        # discrete, which can use different optimizers. Bool may work
        # better, and some algorithms (like BOCS and HARMONICA) are tailored
        # to work on the {0,1} search space. Another option is to do the
        # optimization in a latent probability space and optimize E[perf|probs].
        study_config.search_space.root.add_bool_param(parameter_name)

    study_config.metric_information.append(
        vz.MetricInformation('objective', goal=vz.ObjectiveMetricGoal.MAXIMIZE))
    # Setup client and begin optimization. Vizier Service will be implicitly created.
    study = vz_clients.Study.from_study_config(study_config, owner='kunal', study_id='example2')
    return study

