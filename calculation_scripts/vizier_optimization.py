def vizier_param_dict_to_array(vz_params, parameter_shape):
    ranges = [range(n) for n in parameter_shape]
    array = np.zeros(parameter_shape, dtype=float)
    for indices in iter_product(*ranges):
        index_name = '_'.join([str(n) for n in indices])
        parameter_name = f'value_{index_name}'
        parameter_value = vz_params[parameter_name]
        parameter_value = 0 if parameter_value.lower() == 'false' else 1
        array[indices] = parameter_value
    return array

